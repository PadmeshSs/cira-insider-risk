def preflight(ctx: Ctx) -> dict:
    print("\n=== 0 preflight ===")
    problems = []
    if ctx.processed is None:
        raise SignoffError("CERT_PROCESSED_DIR is not set (in the environment or the repository .env)")
    for profile in ("mid", "full"):
        f = ctx.processed / "features" / f"user_day_{profile}.parquet"
        if not f.exists():
            problems.append(f"missing {f}")
        s = ctx.splits / f"user_split_{profile}_seed{ctx.args.seed}.json"
        if not s.exists():
            problems.append(f"missing split file {s}")
    for name in ("insider_user_days.parquet", "account_user_days.parquet"):
        if not (ctx.processed / "labels" / name).exists():
            problems.append(f"missing label table {name}; run scripts/build_labels.py")
    for ref in (ctx.ch6_refs, ctx.ch7_refs):
        if not ref.exists():
            problems.append(f"missing {ref}")
    if problems:
        raise SignoffError("preflight: " + "; ".join(problems))

    sys.path.insert(0, str(BACKEND))
    from app.tabnet.model_registry import ModelRegistry, RegistryError

    ch6, ch7 = read_json(ctx.ch6_refs), read_json(ctx.ch7_refs)
    tabnet = {}
    reg = ModelRegistry(ctx.models, "tabnet")
    for key in KEYS:
        ref = (ch7.get("runs") or {}).get(key)
        if not ref:
            problems.append(f"no Chapter 7 reference run for {key}")
            continue
        try:
            entry = reg.resolve(ref["registry_version"])
        except RegistryError as exc:
            problems.append(f"TabNet {key} {ref['registry_version']}: {exc} (MODEL_PATH={ctx.models})")
            continue
        bad = reg.verify(entry)
        if bad:
            problems.append(f"TabNet {key} {ref['registry_version']} fails sha256: {bad}")
        if entry.get("run_id") != ref["run_id"]:
            problems.append(f"TabNet {key}: registry {ref['registry_version']} holds run {entry.get('run_id')}, reference says {ref['run_id']}")
        score = ctx.processed / "scores" / "chapter7" / ref["run_id"] / "tabnet.parquet"
        if not score.exists():
            problems.append(f"missing TabNet score file {score}")
        tabnet[key] = {**ref, "split": entry.get("split") or {}}
        g6 = (ch6.get("runs") or {}).get(key, {}).get("gbdt")
        if not g6 or not (ctx.processed / "scores" / "chapter6" / g6 / "gbdt.parquet").exists():
            problems.append(f"Chapter 6 XGBoost reference score file for {key} not found")
    if problems:
        raise SignoffError("preflight: " + "; ".join(problems))
    print(f"  processed: {ctx.processed}\n  models:    {ctx.models}\n  runlog:    {ctx.runlog}")
    print("  Chapter 7 reference TabNet: " + ", ".join(f"{k} {v['registry_version']}" for k, v in tabnet.items()))
    if os.environ.get("CIRA_SERVED_MODEL"):
        print("  NOTE: CIRA_SERVED_MODEL is set; the sign-off ignores it and serves the recorded decision.")
    print("  preflight OK")
    return tabnet


def tests(ctx: Ctx) -> None:
    print("\n=== 1 tests ===")
    if ctx.args.skip_tests:
        print("  skipped (--skip-tests)")
        return
    code, out = ctx.run("pytest", ["-m", "pytest", "-q"], cwd=REPO)
    tail = [line for line in out.splitlines() if " passed" in line or " failed" in line or " error" in line]
    ctx.state["tests"] = {"exit": code, "summary": tail[-1] if tail else None, "at": now()}
    ctx.save()
    if code != 0:
        raise SignoffError("the test suite is not green; fix it before any real run")


def candidates(ctx: Ctx, tabnet: dict) -> dict:
    print("\n=== 2 candidates ===")
    sys.path.insert(0, str(BACKEND))
    from app.tabnet.model_registry import ModelRegistry, RegistryError

    reg = ModelRegistry(ctx.models, "gbdt")
    runs: dict[str, str] = {}
    if ctx.decision.exists():                      # the decision names its candidates; they are final
        decided = read_json(ctx.decision)["candidates"]["gbdt"]
        runs = {k: v["run_id"] for k, v in decided.items()}
        print("  decision exists: candidates are the ones it names")
    for key in KEYS:
        if key in runs:
            continue
        known = ctx.state["candidates"].get(key)
        if known:
            try:
                reg.resolve(known)
                runs[key] = known
                print(f"  {key}: already trained ({known})")
                continue
            except RegistryError:
                print(f"  {key}: recorded run {known} is not registered; training again")
        profile, split = key.split("/")
        argv = ["-m", "app.scoring.gbdt_candidate", "--processed-dir", str(ctx.processed), "--profile", profile,
                "--split", split, "--seed", str(ctx.args.seed), "--splits-dir", str(ctx.splits),
                "--results-dir", str(ctx.results), "--models-dir", str(ctx.models)]
        if split == "time":
            s = tabnet[key]["split"]
            if not (s.get("validation_start") and s.get("test_start")):
                raise SignoffError(f"TabNet {key} registry entry has no time-split dates")
            argv += ["--time-validation-start", s["validation_start"], "--time-test-start", s["test_start"]]
        before = {r.get("run_id") for r in runlog_lines(ctx.runlog) if r.get("stage") == "chapter8_gbdt_candidate"}
        code, _ = ctx.run(f"candidate_{profile}_{split}", argv)
        new = [r for r in runlog_lines(ctx.runlog) if r.get("stage") == "chapter8_gbdt_candidate"
               and r.get("run_id") not in before and r.get("profile") == profile and r.get("split_mode") == split]
        if code != 0 or len(new) != 1 or not new[0].get("registry_version"):
            raise SignoffError(f"candidate {key} did not finish with one registered run (exit {code})")
        runs[key] = new[0]["run_id"]
        ctx.state["candidates"][key] = runs[key]
        ctx.save()
    return runs


def verify_candidates(ctx: Ctx, runs: dict) -> None:
    print("\n=== 3 verify candidates ===")
    for key in KEYS:
        run_id = runs[key]
        done = ctx.state["candidate_verification"].get(key) or {}
        if done.get("run_id") == run_id and done.get("counts", {}).get("FAIL") == 0 and done.get("permutation") == (not ctx.args.skip_permutation):
            print(f"  {key}: already verified ({done['counts']})")
            continue
        profile = key.split("/")[0]
        argv = [str(REPO / "scripts" / "verify_chapter8.py"), "--processed-dir", str(ctx.processed), "--profile", profile,
                "--candidate-run-id", run_id, "--no-decision", "--results-dir", str(ctx.results),
                "--splits-dir", str(ctx.splits), "--models-dir", str(ctx.models), "--ch6-references", str(ctx.ch6_refs),
                "--ch7-references", str(ctx.ch7_refs)]
        if not ctx.args.skip_permutation:
            argv.append("--permutation-test")
        code, out = ctx.run(f"verify_candidate_{key.replace('/', '_')}", argv)
        record = {"run_id": run_id, "exit": code, "counts": verifier_counts(out), "warn": verifier_lines(out, "WARN"),
                  "fail": verifier_lines(out, "FAIL"), "leakage": [x for x in out.splitlines() if " leakage " in x],
                  "permutation": not ctx.args.skip_permutation, "at": now()}
        ctx.state["candidate_verification"][key] = record
        ctx.save()
        if code != 0:
            raise SignoffError(f"candidate {key} ({run_id}) failed verification:\n  " + "\n  ".join(record["fail"]))


def decide(ctx: Ctx, runs: dict) -> None:
    print("\n=== 4 decision (validation only) ===")
    if ctx.decision.exists():
        print(f"  exists: {ctx.decision} (a decision is made once)")
        return
    argv = ["-m", "app.scoring.select", "--processed-dir", str(ctx.processed), "--decision-path", str(ctx.decision),
            "--test-readout-path", str(ctx.readout), "--ch7-references", str(ctx.ch7_refs),
            "--ch6-references", str(ctx.ch6_refs), "--models-dir", str(ctx.models), "--seed", str(ctx.args.seed)]
    for key in KEYS:
        argv += ["--gbdt", f"{key}={runs[key]}"]
    code, _ = ctx.run("select", argv)
    if code != 0 or not ctx.decision.exists():
        raise SignoffError(f"the serving decision was not written (exit {code})")


def test_readout(ctx: Ctx) -> None:
    print("\n=== 5 test readout (once) ===")
    if ctx.readout.exists():
        print(f"  exists: {ctx.readout} (test is read once)")
        return
    argv = ["-m", "app.scoring.select", "--report-test", "--processed-dir", str(ctx.processed),
            "--decision-path", str(ctx.decision), "--test-readout-path", str(ctx.readout),
            "--ch7-references", str(ctx.ch7_refs), "--ch6-references", str(ctx.ch6_refs), "--models-dir", str(ctx.models),
            "--seed", str(ctx.args.seed)]
    code, _ = ctx.run("report_test", argv)
    if code != 0 or not ctx.readout.exists():
        raise SignoffError(f"the test readout was not written (exit {code})")


def batch(ctx: Ctx) -> str:
    print("\n=== 6 batch scoring ===")
    current = sha256(ctx.decision)
    known = ctx.state.get("batch_run_id")
    if known:
        meta = ctx.processed / "scores" / "chapter8" / known / "batch_meta.json"
        if meta.exists() and read_json(meta).get("decision_sha256") == current:
            print(f"  already scored with the current decision ({known})")
            return known
    before = {r.get("batch_run_id") for r in runlog_lines(ctx.runlog) if r.get("stage") == "chapter8_batch_scoring"}
    code, _ = ctx.run("batch", ["-m", "app.scoring.batch", "--processed-dir", str(ctx.processed), "--profile", "full",
                                "--with-shadow", "--splits-dir", str(ctx.splits)])
    new = [r for r in runlog_lines(ctx.runlog) if r.get("stage") == "chapter8_batch_scoring" and r.get("batch_run_id") not in before]
    if code != 0 or len(new) != 1:
        raise SignoffError(f"batch scoring did not finish (exit {code})")
    ctx.state["batch_run_id"] = new[0]["batch_run_id"]
    ctx.save()
    return ctx.state["batch_run_id"]


def final_verify(ctx: Ctx, runs: dict, batch_run_id: str) -> dict:
    print("\n=== 7 verify decision, served model, batch ===")
    argv = [str(REPO / "scripts" / "verify_chapter8.py"), "--processed-dir", str(ctx.processed), "--profile", "full",
            "--candidate-run-id", runs["full/user"], "--batch-run-id", batch_run_id, "--decision-path", str(ctx.decision),
            "--test-readout-path", str(ctx.readout), "--results-dir", str(ctx.results), "--splits-dir", str(ctx.splits),
            "--models-dir", str(ctx.models), "--ch6-references", str(ctx.ch6_refs), "--ch7-references", str(ctx.ch7_refs)]
    code, out = ctx.run("verify_final", argv)
    record = {"exit": code, "counts": verifier_counts(out), "warn": verifier_lines(out, "WARN"), "fail": verifier_lines(out, "FAIL"),
              "detail": [x.strip() for x in out.splitlines() if x.strip()[:4] in ("PASS", "WARN", "FAIL")], "at": now()}
    ctx.state["final_verification"] = record
    ctx.save()
    if code != 0:
        raise SignoffError("final verification failed:\n  " + "\n  ".join(record["fail"]))
    return record


HEALTH_CODE = r"""
import json
from fastapi.testclient import TestClient
from app.main import app
with TestClient(app) as client:
    r = client.get("/health")
print("HEALTH_JSON=" + json.dumps({"code": r.status_code, "body": r.json()}))
"""


def health(ctx: Ctx) -> dict:
    print("\n=== 8 API startup and /health ===")
    code, out = ctx.run("health", ["-c", HEALTH_CODE])
    line = next((x for x in out.splitlines() if x.startswith("HEALTH_JSON=")), None)
    if code != 0 or line is None:
        raise SignoffError(f"the API did not start (exit {code})")
    got = json.loads(line[len("HEALTH_JSON="):])
    body, want = got["body"], read_json(ctx.decision)["outcome"]["served"]
    model = body.get("anomaly_model") or {}
    served = model.get("served") or {}
    ok = (got["code"] == 200 and body.get("status") == "healthy" and model.get("source") == "decision_file"
          and served.get("registry_version") == want["registry_version"] and served.get("model_version") == want["model_version"]
          and served.get("device") == "cpu")
    ctx.state["health"] = {"ok": ok, "status": body.get("status"), "source": model.get("source"),
                           "served": {k: served.get(k) for k in ("model_name", "registry_version", "model_version", "device")},
                           "shadow": [s.get("registry_version") for s in model.get("shadow", [])], "at": now()}
    ctx.save()
    if not ok:
        raise SignoffError(f"/health does not report the decided model on CPU: {json.dumps(ctx.state['health'])}")
    print(f"  /health: healthy, serving {served['model_name']} {served['registry_version']} on CPU")
    return ctx.state["health"]


