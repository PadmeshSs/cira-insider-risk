def _replace(path: Path, old: str, new: str, what: str, manual: list[str]) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if new in text:
        return
    if old not in text:
        manual.append(f"{path}: {what}")
        return
    path.write_text(text.replace(old, new, 1), encoding="utf-8")
    print(f"  updated {path}: {what}")


def finalize(ctx: Ctx) -> int:
    st = ctx.state
    if not st.get("green"):
        raise SignoffError("the last sign-off run was not green; run the sign-off first")
    if not ctx.audit.exists():
        raise SignoffError(f"{ctx.audit} does not exist")
    text = ctx.audit.read_text(encoding="utf-8")
    if TO_EXPLAIN in text:
        n = text.count(TO_EXPLAIN)
        raise SignoffError(f"{ctx.audit} still has {n} '{TO_EXPLAIN}' line(s); explain every WARN first (N27)")
    if DRAFT_MARK in text:
        ctx.audit.write_text(text.replace(DRAFT_MARK + "\n\n", "").replace(DRAFT_MARK, ""), encoding="utf-8")
    served = read_json(ctx.decision)["outcome"]["served"]
    stamp = datetime.now(timezone.utc).strftime("%d %B %Y")
    manual: list[str] = []
    cf = ctx.docs / "docs" / "CARRY_FORWARD.md"
    _replace(cf, "| N27 Chapter 8 status | 8 (until retired) |", "| N27 Chapter 8 status (RETIRED) | - |", "N27 row retired", manual)
    _replace(cf, "## N27. Chapter 8 is PARTIALLY IMPLEMENTED until real runs exist  (from Chapter 8)\n\n",
             "## N27. Chapter 8 is PARTIALLY IMPLEMENTED until real runs exist  (from Chapter 8)\n\n"
             "RETIRED (chapter 8, runs verified; see `docs/audits/chapter_8_audit.md`).\n\n", "N27 marked RETIRED", manual)
    readme = ctx.docs / "README.md"
    _replace(readme, "| 8 | Anomaly scoring service, served-model decision, batch scoring, API model loading | PARTIALLY IMPLEMENTED; synthetic tests pass, CERT runs pending (N27) |",
             f"| 8 | Anomaly scoring service, served-model decision, batch scoring, API model loading | IMPLEMENTED; serving {served['model_name']} {served['registry_version']} |",
             "status row", manual)
    readme_text = readme.read_text(encoding="utf-8") if readme.exists() else ""
    if "docs/audits/chapter_8_audit.md" not in readme_text:
        _replace(readme, "`docs/audits/chapter_7_audit.md` for the chapter reviews",
                 "`docs/audits/chapter_7_audit.md` and `docs/audits/chapter_8_audit.md` for the chapter reviews", "audit link", manual)
    chap = ctx.docs / "docs" / "chapters" / "chapter_8_scoring.md"
    chap_text = chap.read_text(encoding="utf-8") if chap.exists() else ""
    start = chap_text.find("Status: PARTIALLY IMPLEMENTED")
    end = chap_text.find("\n\n", start)
    if start >= 0 and end > start:
        chap_text = chap_text[:start] + (
            f"Status: IMPLEMENTED ({stamp}). Verified on CERT r4.2 with 0 FAIL; the runs, the decision and\n"
            f"every WARN are in `docs/audits/chapter_8_audit.md`. Served model: {served['model_name']}\n"
            f"{served['registry_version']} (`{served['model_version']}`), recorded in\n"
            "`experiments/chapter8_serving_decision.json`. Reported runs: `experiments/chapter8_reference_runs.json`."
        ) + chap_text[end:]
        section = chap_text.find("Real runs (N27), not yet done:")
        if section >= 0:
            chap_text = chap_text[:section] + chap_text[section:].replace("Real runs (N27), not yet done:", "Real runs (N27):", 1).replace("- [ ] ", "- [x] ")
        chap.write_text(chap_text, encoding="utf-8")
        print(f"  updated {chap}: status IMPLEMENTED, real-run checklist ticked")
    elif "Status: IMPLEMENTED" not in chap_text:
        manual.append(f"{chap}: set the status line to IMPLEMENTED")
    st["finalized_at"] = now()
    ctx.save()
    if manual:
        print("\nEdit these by hand (their text no longer matched):\n  " + "\n  ".join(manual))
    print("\nChapter 8 is signed off. Commit:\n"
          "  git add experiments/chapter8_serving_decision.json experiments/chapter8_test_readout.json "
          "experiments/chapter8_reference_runs.json experiments/runlog.jsonl docs/ README.md\n"
          "  git commit -m \"Chapter 8 sign-off: served-model decision, batch scoring, audit\"")
    return 0


