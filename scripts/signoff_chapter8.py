def parse_args(argv: list[str] | None) -> argparse.Namespace:
    load_dotenv(REPO / ".env")
    p = argparse.ArgumentParser(description="CIRA Chapter 8 sign-off")
    p.add_argument("--finalize", action="store_true", help="after reviewing the audit: retire N27 and raise the status")
    p.add_argument("--skip-tests", action="store_true", help="do not run the pytest suite first")
    p.add_argument("--quiet", action="store_true", help="only step headers on the console (full output stays in the logs)")
    p.add_argument("--processed-dir", default=os.getenv("CERT_PROCESSED_DIR"))
    p.add_argument("--models-dir", default=os.getenv("MODEL_PATH", str(REPO / "models" / "saved_models")))
    p.add_argument("--seed", type=int, default=int(os.getenv("CIRA_SEED", "42")))
    p.add_argument("--experiments-dir", default=str(REPO / "experiments"), help=argparse.SUPPRESS)   # tests
    p.add_argument("--docs-root", default=str(REPO), help=argparse.SUPPRESS)                        # tests
    p.add_argument("--skip-permutation", action="store_true", help=argparse.SUPPRESS)               # tests only
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(errors="replace")     # a console that cannot show a character must not stop a run
    except (AttributeError, ValueError):
        pass
    args = parse_args(argv)
    ctx = Ctx(args)
    try:
        if args.finalize:
            return finalize(ctx)
        ctx.state["green"] = False
        ctx.state["started_at"] = now()
        ctx.save()
        tabnet = preflight(ctx)
        tests(ctx)
        runs = candidates(ctx, tabnet)
        verify_candidates(ctx, runs)
        decide(ctx, runs)
        test_readout(ctx)
        batch_run_id = batch(ctx)
        final_verify(ctx, runs, batch_run_id)
        health(ctx)
        audit = record(ctx, runs, batch_run_id)
    except SignoffError as exc:
        print(f"\nRED: {exc}\n\nFix it and run the same command again; finished steps are skipped.", file=sys.stderr)
        return 1
    ctx.state["green"] = True
    ctx.state["finished_at"] = now()
    ctx.save()
    warns = audit.read_text(encoding="utf-8").count(TO_EXPLAIN)
    served = read_json(ctx.decision)["outcome"]["served"]
    print(f"\nGREEN: Chapter 8 ran end to end with 0 FAIL. Serving {served['model_name']} {served['registry_version']}.")
    if warns:
        print(f"Next: open {audit} and replace the {warns} '{TO_EXPLAIN}' line(s) with the reason each WARN is acceptable,")
        print("then run: python ../scripts/signoff_chapter8.py --finalize")
    else:
        print("No WARNs. Read the audit, then run: python ../scripts/signoff_chapter8.py --finalize")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
