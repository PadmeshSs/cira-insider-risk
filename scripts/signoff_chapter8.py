"""Run everything Chapter 8 needs on the real data, in order, and stop at the first failure.

Usage, from backend/ (the script loads the repository's .env for any variable
not already set):

    python ../scripts/signoff_chapter8.py              # run / resume the sign-off
    python ../scripts/signoff_chapter8.py --finalize   # after reviewing the audit: raise the status

Sign-off sequence (CARRY_FORWARD N27, docs/chapters/chapter_8_scoring.md "How to run"):

    0  preflight   env, feature files, labels, split files, Chapter 6/7 reference
                   runs and their score files, TabNet registry versions (sha256)
    1  tests       the full pytest suite (skip with --skip-tests)
    2  candidates  behaviour-only XGBoost at mid/user, mid/time, full/user; the
                   time split uses the dates of the Chapter 7 mid/time run, so
                   both models are scored on the same rows
    3  verify      each candidate: verify_chapter8.py --permutation-test --no-decision
    4  decide      python -m app.scoring.select (validation only)
    5  test        python -m app.scoring.select --report-test (once)
    6  batch       python -m app.scoring.batch --profile full --with-shadow
    7  verify      verify_chapter8.py on decision + served model + batch
    8  health      the FastAPI app starts and /health reports the decided model
    9  record      experiments/chapter8_reference_runs.json and an audit draft
                   (docs/audits/chapter_8_audit.md) written from the output files

Every heavy step runs in its own process, one at a time (HCEA §16), with its
output in experiments/results/chapter8/signoff_logs/. Progress is kept in
experiments/results/chapter8/signoff_state.json, so a re-run skips what is
already done: a candidate that is registered and verified, the decision, the
test readout, a batch made with the current decision. Nothing that already
exists is overwritten, and test is never read twice.

The audit draft contains only numbers copied from the run outputs. Each WARN
the verifier printed becomes a "TO EXPLAIN" line that a person must replace
with the reason it is acceptable. ``--finalize`` refuses while any remain.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BACKEND = REPO / "backend"
KEYS = ("mid/user", "mid/time", "full/user")
TO_EXPLAIN = "TO EXPLAIN"
DRAFT_MARK = "<!-- generated by scripts/signoff_chapter8.py from run outputs -->"


class SignoffError(RuntimeError):
    """A step failed; the sign-off stops here."""


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load_dotenv(path: Path) -> list[str]:
    """Set KEY=VALUE pairs from ``path`` that are not already in the environment."""
    loaded = []
    if not path.exists():
        return loaded
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value
            loaded.append(key)
    return loaded


def read_json(path: Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    tmp.replace(path)


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def runlog_lines(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def fmt(v, nd: int = 3) -> str:
    if v is None:
        return "n/a"
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


class Ctx:
    def __init__(self, args: argparse.Namespace) -> None:
        self.args = args
        exp = Path(args.experiments_dir)
        self.exp = exp
        self.results = exp / "results" / "chapter8"
        self.logs = self.results / "signoff_logs"
        self.state_path = self.results / "signoff_state.json"
        self.decision = exp / "chapter8_serving_decision.json"
        self.readout = exp / "chapter8_test_readout.json"
        self.reference = exp / "chapter8_reference_runs.json"
        self.ch6_refs = exp / "chapter6_reference_runs.json"
        self.ch7_refs = exp / "chapter7_reference_runs.json"
        self.splits = exp / "splits"
        self.docs = Path(args.docs_root)
        self.audit = self.docs / "docs" / "audits" / "chapter_8_audit.md"
        self.processed = Path(args.processed_dir) if args.processed_dir else None
        self.models = Path(args.models_dir)
        self.runlog = Path(os.environ.get("CIRA_RUNLOG", str(exp / "runlog.jsonl")))
        self.state = read_json(self.state_path) if self.state_path.exists() else {}
        self.state.setdefault("candidates", {})
        self.state.setdefault("candidate_verification", {})

    def save(self) -> None:
        self.state["updated_at"] = now()
        write_json(self.state_path, self.state)

    def env(self) -> dict:
        env = dict(os.environ)
        env["MODEL_PATH"] = str(self.models)
        env["CIRA_SERVING_DECISION"] = str(self.decision)
        env["CERT_PROCESSED_DIR"] = str(self.processed)
        env["CIRA_RUNLOG"] = str(self.runlog)
        env.pop("CIRA_SERVED_MODEL", None)      # the sign-off always serves the recorded decision
        env.pop("CIRA_SHADOW_MODEL", None)
        env["PYTHONPATH"] = str(BACKEND) + os.pathsep + env.get("PYTHONPATH", "")
        env["PYTHONIOENCODING"] = "utf-8"       # Windows pipes default to cp1252; the logs are read as UTF-8
        return env

    def run(self, name: str, argv: list[str], *, cwd: Path = BACKEND) -> tuple[int, str]:
        """Run one step in its own process, echoing and logging its output."""
        self.logs.mkdir(parents=True, exist_ok=True)
        log = self.logs / f"{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}_{name}.log"
        print(f"\n>>> {name}: {' '.join(argv)}", flush=True)
        lines = []
        with log.open("w", encoding="utf-8") as fh:
            proc = subprocess.Popen([sys.executable, *argv], cwd=cwd, env=self.env(), stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace")
            for line in proc.stdout:
                fh.write(line)
                lines.append(line)
                if not self.args.quiet:
                    sys.stdout.write(line)
            code = proc.wait()
        print(f"<<< {name}: exit {code}  (log: {log})", flush=True)
        return code, "".join(lines)


def verifier_lines(output: str, status: str) -> list[str]:
    return [line.strip() for line in output.splitlines() if line.strip().startswith(status + " ")]


def verifier_counts(output: str) -> dict:
    for line in reversed(output.splitlines()):
        if " PASS, " in line and " FAIL" in line:
            parts = line.split("->")[0].replace(",", "").split()
            return {parts[i + 1]: int(parts[i]) for i in range(0, 6, 2)}
    return {}


