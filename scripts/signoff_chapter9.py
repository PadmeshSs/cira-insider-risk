def write_reference(ctx: Ctx, rid: str, cal_id: str) -> None:
    write_json(ctx.reference, {
        "description": ("Reported Chapter 9 runs (CARRY_FORWARD N38). Chapter 12 loads risk scores from this run; "
                        "Chapter 16's ablations C/D recombine its components. If anything is re-run for the record, "
                        "change it here and in docs/audits/chapter_9_audit.md."),
        "served": ctx.state["served"],
        "chapter8_batch_run_id": ctx.state["chapter8_batch"],
        "calibration_id": cal_id,
        "cri_run_id": rid,
        "validation_readout": ctx.readout.name,
        "recorded_at": now(),
    })


def _scenario(d: dict | None) -> str:
    return ", ".join(f"s{k} {v}" for k, v in (d or {}).items()) or "-"


def audit_text(ctx: Ctx, rid: str, cal_id: str) -> str:
    cal_meta = read_json(ctx.models / "cri" / cal_id / "calibration.json")
    risk = _risk_meta(ctx, rid)
    r = read_json(ctx.readout)
    rep, ref = cal_meta["report"], cal_meta["reference"]
    served = ctx.state["served"]
    out = [DRAFT_MARK, "", f"# Chapter 9 audit ({datetime.now(timezone.utc).strftime('%d %B %Y')})", "",
           "Scope: Chapter 9 (Contextual Risk Intelligence), checked against the Bible Chapter 9 acceptance",
           "list, HCEA v1.0 §9 and CARRY_FORWARD N1-N39.",
           "Evidence: `experiments/chapter9_cri_calibration.json`, `experiments/chapter9_validation_readout.json`,",
           "`experiments/chapter9_reference_runs.json`, `experiments/runlog.jsonl` and the verifier output (logs",
           "under `experiments/results/chapter9/signoff_logs/`, gitignored). Every number below is copied from those",
           "files by `scripts/signoff_chapter9.py`.", "",
           f"Served model: {served['model_name']} {served['registry_version']} (`{served['model_version']}`), "
           f"from the Chapter 8 decision. Calibration `{cal_id}`; risk run `{rid}`.", "",
           "## Verification record", "", "| What | Verifier |", "|---|---|"]
    for key, what in (("verify", "calibration + risk run, before labels"), ("verify_with_readout", "including the readout")):
        c = ctx.state.get(key, {}).get("counts", {})
        out.append(f"| {what} | {c.get('PASS')} PASS, {c.get('WARN')} WARN, {c.get('FAIL')} FAIL |")
    out.append(f"| test suite | {ctx.state.get('tests', 'skipped')} |")
    h = ctx.state.get("health", {})
    out.append(f"| /health | {'SKIPPED (tests-only flag; never acceptable for the real sign-off)' if h.get('skipped') else h.get('status', 'n/a') + ', CRI ' + str(h.get('cri'))} |")
    out += ["", "WARNs and why they are acceptable:", ""]
    warns = sorted(set(ctx.state.get("verify", {}).get("warn", []) + ctx.state.get("verify_with_readout", {}).get("warn", [])))
    out += [f"- `{w}`: {TO_EXPLAIN}" for w in warns] or ["- none."]
    out += ["", "## Calibration (label-free)", "",
            f"Reference: {ref['rows']} validation user-days ({ref['users']} users, {ref['days']} days) of Chapter 8 batch "
            f"`{cal_meta['source_batch']['batch_run_id']}`. Maximum reachable rarity {fmt(ref['max_reachable_rarity'])} "
            f"(D = {cal_meta['rarity_decades']}).", "",
            "| model_split | rows | q0.5 | q0.9 | q0.99 | q0.999 | max |", "|---|---|---|---|---|---|---|"]
    for split, q in rep["served_score_quantiles_by_model_split"].items():
        out.append(f"| {split} | {q.get('rows')} | " + " | ".join(f"{q.get(k, float('nan')):.3g}" for k in ("0.5", "0.9", "0.99", "0.999", "max")) + " |")
    ctx_rep = rep["context_on_reference"]
    out += ["", f"Context on the reference: historical null share {fmt(ctx_rep['historical_null_share'])}, peer null share "
            f"{fmt(ctx_rep['peer_null_share'])}, no LDAP row {fmt(ctx_rep['user_context_null_share'])}, privileged user-days "
            f"{fmt(ctx_rep['privileged_user_day_share'], 4)} ({ctx_rep['privileged_users']} users).", ""]
    sv = rep.get("served_vs_shadow")
    if sv:
        out += ["### Served vs shadow on the same validation user-days (N32 monitoring)", "",
                f"Shadow {sv['shadow_model']}, {sv['rows']} rows. Spearman {fmt(sv['spearman_rank_correlation'])}; "
                f"top-1% overlap {fmt(sv['top_1pct_overlap'])}; share of shadow scores at or above the served model's "
                f"99th percentile {fmt(sv['share_of_shadow_at_or_above_served_q99'], 4)}, and the reverse "
                f"{fmt(sv['share_of_served_at_or_above_shadow_q99'], 4)}; mean daily top-1 Jaccard "
                f"{fmt(sv['daily_top_k_agreement']['1']['mean_jaccard'])}, top-5 {fmt(sv['daily_top_k_agreement']['5']['mean_jaccard'])}.", ""]
    s = risk["summary"]
    out += ["## Risk run (label-free)", "",
            f"{s['rows']} user-days. Severity: " + ", ".join(f"{k} {v}" for k, v in s["severity"].items()) + ".",
            f"Effective weights: " + ", ".join(f"{k} {v:.3f}" for k, v in risk["effective_weights"].items()) + ".",
            "Unavailable: " + "; ".join(f"{k} ({v})" for k, v in risk["unavailable_components"].items()) + ".", ""]
    for split, vol in s["daily_volume_out_of_sample"].items():
        h, c = vol["HIGH_or_above"], vol["CRITICAL"]
        out.append(f"- {split}: HIGH or above per day median {h.get('median')}, p95 {h.get('p95')}, max {h.get('max')}; "
                   f"CRITICAL per day median {c.get('median')}, max {c.get('max')}")
    out += ["", f"## Validation readout ({r['rows']} rows, {r['positives']} malicious user-days, chance {fmt(r['chance_pr_auc'], 4)})", "",
            "| Ranking | PR-AUC | ROC-AUC (secondary) | Recall@1 | Caught@1 | Caught@5 | Days at top-1 by scenario | Insiders at top-1 by scenario |",
            "|---|---|---|---|---|---|---|---|"]
    for name, m in r["models"].items():
        out.append(f"| {name} | {fmt(m['pr_auc'])} | {fmt(m['roc_auc_secondary'])} | {fmt(m['recall_at_1'])} | "
                   f"{m['insiders_caught_at_1']} | {m['insiders_caught_at_5']} | {_scenario(m['days_by_scenario_at_1'])} | "
                   f"{_scenario(m['caught_by_scenario_at_1'])} |")
    for name, m in (r.get("chapter8_reference_rows") or {}).items():
        out.append(f"| {name} anomaly score (Ch8 evidence, not a CRI) | {fmt(m['pr_auc'])} | | | {m['insiders_caught_at_1']} | | "
                   f"{_scenario(m['recall_by_scenario_at_1'])} | {_scenario(m['caught_by_scenario_at_1'])} |")
    b = r["bands"]["cri:default"]
    out += ["", "Default CRI as a band alert (primary view):", ""]
    for band in ("HIGH_or_above", "CRITICAL"):
        x = b[band]
        out.append(f"- {band}: {x['alerts']} alerts, precision {fmt(x['precision'])}, recall {fmt(x['recall'])}, insiders "
                   f"caught {x['per_user']['caught']}/{x['per_user']['insiders']}, alerts per day median "
                   f"{x['alerts_per_day'].get('median')}, max {x['alerts_per_day'].get('max')}")
    out += ["", f"Harness: " + "; ".join(f"{h['check']}: {'PASS' if h['ok'] else ('n/a' if h['ok'] is None else 'FAIL')}"
                                        for h in r["harness"]) + ".", "",
            f"Guard {r['guard']['version']}: " + ("no warning." if not r["guard"]["warnings"] else
                                                  f"{len(r['guard']['warnings'])} warning(s), listed with the WARNs above."),
            "", "## Notes", "",
            "- One seed per model; no confidence intervals yet. Chapter 16 adds seeds and bootstrap intervals (C6-2, C7-7).",
            "- The CRI was not read on test. Its test readout is Chapter 16's ablation C (N37).",
            "- Any scenario-3 difference from user_context is expected by construction and is not evidence (N36).",
            "- Rows tagged `train` are in-sample; nothing above quotes detection from them (N31).", ""]
    return "\n".join(out)


def record(ctx: Ctx, rid: str, cal_id: str) -> Path:
    print("\n=== 8 record ===")
    write_reference(ctx, rid, cal_id)
    text = audit_text(ctx, rid, cal_id)
    target = ctx.audit
    if target.exists() and DRAFT_MARK not in target.read_text(encoding="utf-8"):
        target = target.with_name("chapter_9_audit.generated.md")
        print(f"  {ctx.audit} was edited by hand; the fresh draft goes to {target} instead")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"  written: {target}")
    return target


