def preflight(ctx: Ctx) -> dict:
    print("=== 0 preflight ===")
    if ctx.processed is None:
        raise SignoffError("CERT_PROCESSED_DIR is not set (in .env or the environment)")
    if not ctx.decision.exists():
        raise SignoffError(f"{ctx.decision} not found; Chapter 8 must be signed off first")
    served = read_json(ctx.decision)["outcome"]["served"]
    root = ctx.processed / "scores" / "chapter8"
    batches = []
    for d in sorted(root.iterdir()) if root.exists() else []:
        meta = d / "batch_meta.json"
        if meta.exists():
            m = read_json(meta)
            if m.get("profile") == ctx.args.profile:
                batches.append((d.name, m))
    if not batches:
        raise SignoffError(f"no {ctx.args.profile} Chapter 8 batch under {root}; run `python -m app.scoring.batch "
                           f"--profile {ctx.args.profile} --with-shadow`")
    batch_id, bm = batches[-1]
    if (bm["served"]["model_name"], bm["served"]["registry_version"]) != (served["model_name"], served["registry_version"]):
        raise SignoffError(f"newest batch {batch_id} was scored by {bm['served']['model_name']}:"
                           f"{bm['served']['registry_version']}, the decision serves {served['model_name']}:"
                           f"{served['registry_version']}")
    if not bm.get("shadow"):
        print(f"  note: batch {batch_id} has no shadow rows; the served-vs-shadow report will be empty")
    needed = {
        "features": ctx.processed / "features" / f"user_day_{ctx.args.profile}.parquet",
        "LDAP context": ctx.processed / "context" / "ldap_user_month.parquet",
        "primary labels": ctx.processed / "labels" / "insider_user_days.parquet",
        "account labels": ctx.processed / "labels" / "account_user_days.parquet",
    }
    for what, path in needed.items():
        if not path.exists():
            raise SignoffError(f"{what} missing: {path}")
    if str(BACKEND) not in sys.path:
        sys.path.insert(0, str(BACKEND))
    from app.cri.config import CRIConfig, CRIConfigError   # stdlib only; no numpy

    try:
        overrides = dict(CRIConfig.from_env().overrides)
    except CRIConfigError as exc:
        raise SignoffError(f"CRI configuration in .env or the environment is invalid: {exc}")
    if overrides:
        raise SignoffError(
            "CRI_* values in .env or the environment differ from the Chapter 9 defaults, which were fixed before any "
            f"CRI number existed (N37): {overrides}. Replace the CRI block of .env with the one in .env.example "
            "(or delete those lines) and run again. A deliberate change of weights is a new configuration: change "
            "the defaults in backend/app/cri/config.py and say why in the chapter document")
    print(f"  served {served['model_name']} {served['registry_version']} ({served['model_version']}); "
          f"Chapter 8 batch {batch_id}")
    ctx.state["served"] = served
    ctx.state["chapter8_batch"] = batch_id
    ctx.save()
    return served


def tests(ctx: Ctx) -> None:
    print("\n=== 1 tests ===")
    if ctx.args.skip_tests:
        print("  skipped (--skip-tests)")
        return
    code, out = ctx.run("pytest", ["-m", "pytest", "-q"], cwd=REPO)
    if code != 0:
        raise SignoffError("the test suite failed; see the log")
    ctx.state["tests"] = next((l.strip() for l in reversed(out.splitlines()) if " passed" in l), "passed")
    ctx.save()


def calibrate(ctx: Ctx, served: dict) -> str:
    print("\n=== 2 calibrate ===")
    if ctx.pin.exists():
        cur = read_json(ctx.pin)["current"]
        if cur["model"].get("model_version") != served["model_version"]:
            raise SignoffError(
                f"{ctx.pin} pins calibration {cur['calibration_id']} for {cur['model'].get('model_version')}, but the "
                f"served model is {served['model_version']}. Replace it deliberately with `python -m app.cri.calibrate "
                "--supersede \"<reason>\"` (N29); the sign-off never supersedes on its own")
        if cur["source_batch_run_id"] != ctx.state["chapter8_batch"]:
            raise SignoffError(f"the pinned calibration was fitted on batch {cur['source_batch_run_id']}, the newest "
                               f"batch is {ctx.state['chapter8_batch']}; pass it explicitly or supersede the calibration")
        print(f"  calibration {cur['calibration_id']} already pinned for the served model; skipped")
        ctx.state["calibration_id"] = cur["calibration_id"]
        ctx.save()
        return cur["calibration_id"]
    extra = ["--min-reference-rows", str(ctx.args.min_reference_rows)] if ctx.args.min_reference_rows else []
    code, _ = ctx.run("calibrate", ["-m", "app.cri.calibrate", *ctx.common(), "--batch-run-id", ctx.state["chapter8_batch"],
                                    "--models-dir", str(ctx.models), "--pin-path", str(ctx.pin), *extra])
    if code != 0:
        raise SignoffError("calibration refused; see the log")
    cal_id = read_json(ctx.pin)["current"]["calibration_id"]
    ctx.state["calibration_id"] = cal_id
    ctx.save()
    return cal_id


def _risk_meta(ctx: Ctx, cri_run_id: str) -> dict:
    return read_json(ctx.processed / "risk" / "chapter9" / cri_run_id / "cri_meta.json")


def batch(ctx: Ctx, cal_id: str) -> str:
    print("\n=== 3 batch ===")
    rid = ctx.state.get("cri_run_id")
    if rid and (ctx.processed / "risk" / "chapter9" / rid / "cri_meta.json").exists():
        m = _risk_meta(ctx, rid)
        if m["calibration"]["calibration_id"] == cal_id and m.get("is_calibrated_default"):
            print(f"  risk run {rid} already made with calibration {cal_id}; skipped")
            return rid
    code, out = ctx.run("cri_batch", ["-m", "app.cri.batch", *ctx.common(), "--batch-run-id", ctx.state["chapter8_batch"],
                                      "--models-dir", str(ctx.models), "--pin-path", str(ctx.pin)])
    if code != 0:
        raise SignoffError("the CRI batch refused; see the log")
    line = next((l for l in out.splitlines() if l.startswith("[cri] ") and ": " in l and "-cri-" in l), "")
    rid = line.split("[cri] ", 1)[1].split(":", 1)[0].strip() if line else None
    if not rid:
        raise SignoffError("could not read the risk run id from the batch output")
    if not _risk_meta(ctx, rid).get("is_calibrated_default"):
        raise SignoffError(f"risk run {rid} is not the calibrated default configuration; check .env for CRI_* overrides")
    ctx.state["cri_run_id"] = rid
    ctx.save()
    return rid


def verify(ctx: Ctx, rid: str, *, with_readout: bool) -> dict:
    name = "verify_with_readout" if with_readout else "verify"
    print(f"\n=== {'6' if with_readout else '4'} {name} ===")
    argv = [str(REPO / "scripts" / "verify_chapter9.py"), *ctx.common(), "--cri-run-id", rid,
            "--pin-path", str(ctx.pin), "--models-dir", str(ctx.models), "--readout-path", str(ctx.readout),
            "--results-dir", str(ctx.results)]
    if not with_readout:
        argv.append("--no-readout")
    code, out = ctx.run(name, argv)
    counts = verifier_counts(out)
    if code != 0 or counts.get("FAIL", 1) != 0:
        raise SignoffError(f"verifier: {counts or 'no summary line'}; fix every FAIL first")
    record = {"counts": counts, "warn": verifier_lines(out, "WARN")}
    ctx.state[name] = record
    ctx.save()
    return record


def readout(ctx: Ctx, rid: str) -> dict:
    print("\n=== 5 readout ===")
    if ctx.readout.exists():
        r = read_json(ctx.readout)
        if r.get("cri_run_id") != rid:
            raise SignoffError(f"{ctx.readout} is for risk run {r.get('cri_run_id')}, not {rid}; the readout is written "
                               "once (N37). Supersede it deliberately with `python -m app.cri.evaluate --supersede`")
        print("  validation readout already written for this risk run; skipped")
        return r
    code, _ = ctx.run("readout", ["-m", "app.cri.evaluate", *ctx.common(), "--cri-run-id", rid,
                                  "--decision-path", str(ctx.decision), "--readout-path", str(ctx.readout),
                                  "--results-dir", str(ctx.results)])
    if code != 0:
        raise SignoffError("the validation readout refused; see the log")
    return read_json(ctx.readout)


def health(ctx: Ctx, cal_id: str) -> dict:
    print("\n=== 7 health ===")
    if ctx.args.skip_health:
        print("  skipped (--skip-health, tests only: the synthetic world has no registered model to load)")
        ctx.state["health"] = {"skipped": True}
        ctx.save()
        return {}
    probe = ("import json\nfrom fastapi.testclient import TestClient\nfrom app.main import app\n"
             "with TestClient(app) as c:\n    print('HEALTH ' + json.dumps(c.get('/health').json()))\n")
    code, out = ctx.run("health", ["-c", probe])
    line = next((l for l in out.splitlines() if l.startswith("HEALTH ")), None)
    if code != 0 or line is None:
        raise SignoffError("the API did not start; see the log")
    body = json.loads(line[len("HEALTH "):])
    cri = body.get("cri") or {}
    if cri.get("status") != "loaded" or (cri.get("calibration") or {}).get("calibration_id") != cal_id:
        raise SignoffError(f"/health does not report the CRI with calibration {cal_id}: {cri}")
    print(f"  /health: {body['status']}, CRI loaded with {cal_id}")
    ctx.state["health"] = {"status": body["status"], "cri": "loaded", "calibration_id": cal_id}
    ctx.save()
    return body


