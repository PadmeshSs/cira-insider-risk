"""Run everything Chapter 9 needs on the real data, in order, and stop at the first failure.

Usage, from backend/ (the script loads the repository's .env for any variable
not already set):

    python ../scripts/signoff_chapter9.py              # run / resume the sign-off
    python ../scripts/signoff_chapter9.py --finalize   # after reviewing the audit: raise the status

Sign-off sequence (CARRY_FORWARD N38, docs/chapters/chapter_9_cri.md "How to run"):

    0  preflight   env, the Chapter 8 decision, a full Chapter 8 batch scored by
                   the served model (with shadow rows), features, LDAP, labels
    1  tests       the full pytest suite (skip with --skip-tests)
    2  calibrate   python -m app.cri.calibrate --profile full (label-free)
    3  batch       python -m app.cri.batch --profile full (label-free)
    4  verify      verify_chapter9.py --no-readout, 0 FAIL, before any label is read
    5  readout     python -m app.cri.evaluate --profile full (validation only, once)
    6  verify      verify_chapter9.py including the readout, 0 FAIL
    7  health      the FastAPI app starts and /health reports the CRI as loaded
    8  record      experiments/chapter9_reference_runs.json and an audit draft
                   (docs/audits/chapter_9_audit.md) written from the output files

Every step runs in its own process, one at a time (HCEA §16); its output is
kept in experiments/results/chapter9/signoff_logs/. Progress is kept in
experiments/results/chapter9/signoff_state.json, so a re-run skips what is
already done. Nothing that exists is overwritten: an existing calibration
pin for another model stops the run (replace it deliberately with
``calibrate --supersede``), and the validation readout is written once.

The served model is always the one in the Chapter 8 decision file:
CIRA_SERVED_MODEL is ignored here, as in the Chapter 8 sign-off.

The audit draft contains only numbers copied from the output files. Every
WARN becomes a "TO EXPLAIN" line; ``--finalize`` refuses while any remain.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BACKEND = REPO / "backend"
TO_EXPLAIN = "TO EXPLAIN"
DRAFT_MARK = "<!-- generated by scripts/signoff_chapter9.py from run outputs -->"
STATUS_PENDING = "| 9 | Contextual Risk Intelligence (CRI), Asset entity | PARTIALLY IMPLEMENTED; synthetic tests pass, CERT runs pending (N38) |"
N38_HEADING = "## N38. Chapter 9 is PARTIALLY IMPLEMENTED until real runs exist  (from Chapter 9)\n\n"


class SignoffError(RuntimeError):
    """A step failed; the sign-off stops here."""


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load_dotenv(path: Path) -> list[str]:
    loaded = []
    if not path.exists():
        return loaded
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value
            loaded.append(key)
    return loaded


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    tmp.replace(path)


def fmt(v, nd: int = 3) -> str:
    if v is None:
        return "n/a"
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def verifier_counts(output: str) -> dict:
    for line in reversed(output.splitlines()):
        if " PASS, " in line and " FAIL" in line and "[verify chapter9]" in line:
            parts = line.split("]", 1)[1].split("->")[0].replace(",", "").split()
            return {parts[i + 1]: int(parts[i]) for i in range(0, 6, 2)}
    return {}


def verifier_lines(output: str, status: str) -> list[str]:
    return [line.strip() for line in output.splitlines() if line.strip().startswith(status + " ")]


class Ctx:
    def __init__(self, args: argparse.Namespace) -> None:
        self.args = args
        exp = Path(args.experiments_dir)
        self.exp = exp
        self.results = exp / "results" / "chapter9"
        self.logs = self.results / "signoff_logs"
        self.state_path = self.results / "signoff_state.json"
        self.decision = exp / "chapter8_serving_decision.json"
        self.pin = exp / "chapter9_cri_calibration.json"
        self.readout = exp / "chapter9_validation_readout.json"
        self.reference = exp / "chapter9_reference_runs.json"
        self.docs = Path(args.docs_root)
        self.audit = self.docs / "docs" / "audits" / "chapter_9_audit.md"
        self.processed = Path(args.processed_dir) if args.processed_dir else None
        self.models = Path(args.models_dir)
        self.runlog = Path(os.environ.get("CIRA_RUNLOG", str(exp / "runlog.jsonl")))
        self.state = read_json(self.state_path) if self.state_path.exists() else {}

    def save(self) -> None:
        self.state["updated_at"] = now()
        write_json(self.state_path, self.state)

    def env(self) -> dict:
        env = dict(os.environ)
        env["MODEL_PATH"] = str(self.models)
        env["CIRA_SERVING_DECISION"] = str(self.decision)
        env["CIRA_CRI_CALIBRATION"] = str(self.pin)
        env["CERT_PROCESSED_DIR"] = str(self.processed)
        env["CIRA_RUNLOG"] = str(self.runlog)
        env.pop("CIRA_SERVED_MODEL", None)
        env.pop("CIRA_SHADOW_MODEL", None)
        env["PYTHONPATH"] = str(BACKEND) + os.pathsep + env.get("PYTHONPATH", "")
        env["PYTHONIOENCODING"] = "utf-8"
        return env

    def run(self, name: str, argv: list[str], *, cwd: Path = BACKEND) -> tuple[int, str]:
        self.logs.mkdir(parents=True, exist_ok=True)
        log = self.logs / f"{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}_{name}.log"
        print(f"\n>>> {name}: {' '.join(argv)}", flush=True)
        lines = []
        with log.open("w", encoding="utf-8") as fh:
            proc = subprocess.Popen([sys.executable, *argv], cwd=cwd, env=self.env(), stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace")
            for line in proc.stdout:
                fh.write(line)
                lines.append(line)
                if not self.args.quiet:
                    sys.stdout.write(line)
            code = proc.wait()
        print(f"<<< {name}: exit {code}  (log: {log})", flush=True)
        return code, "".join(lines)

    def common(self) -> list[str]:
        return ["--processed-dir", str(self.processed), "--profile", self.args.profile]


