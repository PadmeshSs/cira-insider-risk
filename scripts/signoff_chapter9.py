def _replace(path: Path, old: str, new: str, what: str, manual: list[str]) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if new in text:
        return
    if old not in text:
        manual.append(f"{path}: {what}")
        return
    path.write_text(text.replace(old, new, 1), encoding="utf-8")
    print(f"  updated {path}: {what}")


def finalize(ctx: Ctx) -> int:
    st = ctx.state
    if not st.get("green"):
        raise SignoffError("the last sign-off run was not green; run the sign-off first")
    if not ctx.audit.exists():
        raise SignoffError(f"{ctx.audit} does not exist")
    text = ctx.audit.read_text(encoding="utf-8")
    if TO_EXPLAIN in text:
        raise SignoffError(f"{ctx.audit} still has {text.count(TO_EXPLAIN)} '{TO_EXPLAIN}' line(s); explain every WARN first (N38)")
    if DRAFT_MARK in text:
        ctx.audit.write_text(text.replace(DRAFT_MARK + "\n\n", "").replace(DRAFT_MARK, ""), encoding="utf-8")
    served, cal_id = st["served"], st["calibration_id"]
    stamp = datetime.now(timezone.utc).strftime("%d %B %Y")
    manual: list[str] = []
    cf = ctx.docs / "docs" / "CARRY_FORWARD.md"
    _replace(cf, "| N38 Chapter 9 status | 9 (until retired) |", "| N38 Chapter 9 status (RETIRED) | - |", "N38 row retired", manual)
    _replace(cf, N38_HEADING, N38_HEADING + "RETIRED (chapter 9, runs verified; see `docs/audits/chapter_9_audit.md`).\n\n",
             "N38 marked RETIRED", manual)
    readme = ctx.docs / "README.md"
    _replace(readme, STATUS_PENDING,
             f"| 9 | Contextual Risk Intelligence (CRI), Asset entity | IMPLEMENTED; calibrated for {served['model_name']} "
             f"{served['registry_version']} |", "status row", manual)
    chap = ctx.docs / "docs" / "chapters" / "chapter_9_cri.md"
    chap_text = chap.read_text(encoding="utf-8") if chap.exists() else ""
    start = chap_text.find("Status: PARTIALLY IMPLEMENTED")
    end = chap_text.find("\n\n", start)
    if start >= 0 and end > start:
        chap_text = chap_text[:start] + (
            f"Status: IMPLEMENTED ({stamp}). Verified on CERT r4.2 with 0 FAIL; the runs, the validation\n"
            f"readout and every WARN are in `docs/audits/chapter_9_audit.md`. Calibration `{cal_id}` for\n"
            f"{served['model_name']} {served['registry_version']} (`{served['model_version']}`). Reported runs:\n"
            "`experiments/chapter9_reference_runs.json`."
        ) + chap_text[end:]
        section = chap_text.find("Real runs (N38), not yet done:")
        if section >= 0:
            chap_text = chap_text[:section] + chap_text[section:].replace("Real runs (N38), not yet done:", "Real runs (N38):", 1).replace("- [ ] ", "- [x] ")
        chap.write_text(chap_text, encoding="utf-8")
        print(f"  updated {chap}: status IMPLEMENTED, real-run checklist ticked")
    elif "Status: IMPLEMENTED" not in chap_text:
        manual.append(f"{chap}: set the status line to IMPLEMENTED")
    st["finalized_at"] = now()
    ctx.save()
    if manual:
        print("\nEdit these by hand (their text no longer matched):\n  " + "\n  ".join(manual))
    print("\nChapter 9 is signed off. Commit:\n"
          "  git add experiments/chapter9_cri_calibration.json experiments/chapter9_validation_readout.json "
          "experiments/chapter9_reference_runs.json experiments/runlog.jsonl docs/ README.md\n"
          "  git commit -m \"Chapter 9 sign-off: CRI calibration, risk batch, validation readout, audit\"")
    return 0


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    pre = argparse.ArgumentParser(add_help=False)
    pre.add_argument("--dotenv", default=str(REPO / ".env"))
    load_dotenv(Path(pre.parse_known_args(argv)[0].dotenv))
    p = argparse.ArgumentParser(description="CIRA Chapter 9 sign-off")
    p.add_argument("--dotenv", default=str(REPO / ".env"), help=argparse.SUPPRESS)                   # tests
    p.add_argument("--finalize", action="store_true", help="after reviewing the audit: retire N38 and raise the status")
    p.add_argument("--skip-tests", action="store_true")
    p.add_argument("--quiet", action="store_true")
    p.add_argument("--processed-dir", default=os.getenv("CERT_PROCESSED_DIR"))
    p.add_argument("--models-dir", default=os.getenv("MODEL_PATH", str(REPO / "models" / "saved_models")))
    p.add_argument("--profile", default="full", help=argparse.SUPPRESS)                              # tests only
    p.add_argument("--experiments-dir", default=str(REPO / "experiments"), help=argparse.SUPPRESS)   # tests
    p.add_argument("--docs-root", default=str(REPO), help=argparse.SUPPRESS)                        # tests
    p.add_argument("--skip-health", action="store_true", help=argparse.SUPPRESS)                    # tests only
    p.add_argument("--min-reference-rows", type=int, default=None, help=argparse.SUPPRESS)          # tests only
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(errors="replace")
    except (AttributeError, ValueError):
        pass
    args = parse_args(argv)
    ctx = Ctx(args)
    try:
        if args.finalize:
            return finalize(ctx)
        ctx.state["green"] = False
        ctx.state["started_at"] = now()
        ctx.save()
        served = preflight(ctx)
        tests(ctx)
        cal_id = calibrate(ctx, served)
        rid = batch(ctx, cal_id)
        verify(ctx, rid, with_readout=False)
        readout(ctx, rid)
        verify(ctx, rid, with_readout=True)
        health(ctx, cal_id)
        audit = record(ctx, rid, cal_id)
    except SignoffError as exc:
        print(f"\nRED: {exc}\n\nFix it and run the same command again; finished steps are skipped.", file=sys.stderr)
        return 1
    ctx.state["green"] = True
    ctx.state["finished_at"] = now()
    ctx.save()
    warns = audit.read_text(encoding="utf-8").count(TO_EXPLAIN)
    print("\nGREEN: Chapter 9 ran end to end with 0 FAIL.")
    if warns:
        print(f"Next: open {audit} and replace the {warns} '{TO_EXPLAIN}' line(s) with the reason each WARN is acceptable,")
        print("then run: python ../scripts/signoff_chapter9.py --finalize")
    else:
        print("No WARNs. Read the audit, then run: python ../scripts/signoff_chapter9.py --finalize")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
